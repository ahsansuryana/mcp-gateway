// PLAN.md S1.5: exports gateway.schema.json from the zod schema so editors can
// validate gateway.json against it.
//
// zod v4's JSON Schema target is draft 2020-12, which is also the default dialect the
// MCP spec uses for tool input schemas
// (verified: docs/ref/spec-2026-07-28-basic-index.md "JSON Schema Usage" / Schema Dialect).

import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { z } from 'zod';

import { gatewayConfigSchema } from '../src/config/schema.js';

const target = new URL('../gateway.schema.json', import.meta.url);
const configTarget = new URL('../docs/CONFIG.md', import.meta.url);

const schema = z.toJSONSchema(gatewayConfigSchema, {
  // verified: node_modules/zod/v4/core/to-json-schema.d.cts (JSONSchemaGeneratorParams.target)
  target: 'draft-2020-12',
  // The config file is what a human writes; describe the INPUT shape, so defaults are
  // advertised as defaults rather than as required values.
  // verified: node_modules/zod/v4/core/to-json-schema.d.cts (JSONSchemaGeneratorParams.io)
  io: 'input',
});

const document = {
  $schema: 'https://json-schema.org/draft/2020-12/schema',
  $id: 'https://mcp.example.com/schemas/gateway.schema.json',
  title: 'mcp-gateway configuration',
  description:
    'Configuration for mcp-gateway. See docs/CONFIG.md. Strings support {env:NAME} and {file:path} substitution.',
  ...schema,
};

writeFileSync(fileURLToPath(target), `${JSON.stringify(document, null, 2)}\n`, 'utf8');
process.stdout.write(`wrote ${fileURLToPath(target)}\n`);

// PLAN.md S7.5: docs/CONFIG.md is GENERATED from the same schema, so it cannot drift from
// what the gateway actually accepts. B-16 wanted this checked in CI; generating it is what
// makes such a check possible.
writeFileSync(fileURLToPath(configTarget), renderConfigDoc(document), 'utf8');
process.stdout.write(`wrote ${fileURLToPath(configTarget)}\n`);
/** Renders a reference table for every top-level and nested property of the schema. */
function renderConfigDoc(doc: Record<string, unknown>): string {
  const lines: string[] = [];
  lines.push('<!-- GENERATED by scripts/gen-schema.ts from src/config/schema.ts. Do not edit. -->');
  lines.push('');
  lines.push('# Configuration reference');
  lines.push('');
  lines.push('Generated from `gateway.schema.json`. Every row below is enforced by the gateway at');
  lines.push('startup: an invalid value is a startup error naming the key path.');
  lines.push('');
  lines.push('Strings support `{env:NAME}` and `{file:path}` substitution (PLAN.md D7), applied');
  lines.push('before validation, so secrets need not live in the file.');
  lines.push('');
  lines.push('See `gateway.example.json` for a working example.');
  lines.push('');
  lines.push(renderSection(doc, 'Root', 3));
  lines.push('');
  lines.push('## Environment variables');
  lines.push('');
  lines.push('| Variable | Required | Purpose |');
  lines.push('|---|---|---|');
  // ADR 0012 moved the default off ./gateway.json and added GATEWAY_HOME; ADR 0013 left this
  // list stale, claiming a default the resolver has not used for two sprints and omitting a
  // variable the Docker image sets. Kept here rather than hand-edited so regenerating cannot
  // put the old text back.
  lines.push('| `GATEWAY_CONFIG` | no | Path to the config file. Skipped when missing, not fatal. |');
  lines.push('| `GATEWAY_HOME` | no | Where `.mcp-gateway/` lives. Defaults to your home directory. The Docker image sets it to `/home/node`. |');
  lines.push('| `GATEWAY_TOKEN_KEY` | **yes, when any upstream sets `oauth`** | Base64 32-byte AES-256-GCM key protecting the upstream token store. Generate with `openssl rand -base64 32`. Cannot be rotated. |');
  lines.push('| `GATEWAY_TOKEN_STORE` | no | Overrides the token store path. Default `data/tokens.enc.json` beside the config file. |');
  lines.push('');
  lines.push('`GATEWAY_API_KEY` is referenced through `{env:GATEWAY_API_KEY}` in the `gateway.example.json`');
  lines.push('that `mcp-gateway init` writes; it is not read by the gateway directly.');
  lines.push('');
  lines.push('## Runtime flags');
  lines.push('');
  lines.push('`serve` also accepts `--hostname`, `--port` and `--public-url`, which override the');
  lines.push('corresponding `gateway` fields for that process only and are never written back to the');
  lines.push('file. See `docs/OPERATIONS.md`.');
  lines.push('');
  return `${lines.join('\n')}\n`;
}

function renderSection(schema: Record<string, unknown>, label: string, depth: number): string {
  const out: string[] = [];
  out.push(`${'#'.repeat(depth)} ${label}`);
  out.push('');
  const properties = (schema['properties'] as Record<string, Record<string, unknown>> | undefined) ?? {};
  const required = new Set((schema['required'] as string[] | undefined) ?? []);
  if (Object.keys(properties).length === 0) return `${out.join('\n')}\n`;

  out.push('| Field | Type | Required | Default | Notes |');
  out.push('|---|---|---|---|---|');
  for (const [name, property] of Object.entries(properties)) {
    out.push(
      `| \`${name}\` | ${describeType(property)} | ${required.has(name) ? 'yes' : 'no'} | ${formatDefault(property)} | ${describe(property)} |`,
    );
  }
  out.push('');

  for (const [name, property] of Object.entries(properties)) {
    if (property.properties !== undefined) {
      out.push(renderSection(property, `\`${name}\``, depth + 1));
    }
  }
  return `${out.join('\n')}\n`;
}

function describeType(property: Record<string, unknown>): string {
  if (Array.isArray(property['anyOf'])) {
    return (property['anyOf'] as Record<string, unknown>[]).map(describeType).join(' | ');
  }
  if (Array.isArray(property['oneOf'])) {
    return (property['oneOf'] as Record<string, unknown>[]).map(describeType).join(' | ');
  }
  if (typeof property['type'] === 'string') {
    const values = property['enum'];
    return Array.isArray(values) && values.length > 0
      ? values.map((v) => `\`${String(v)}\``).join(' | ')
      : property['type'];
  }
  if (typeof property['$ref'] === 'string') {
    return String(property['$ref']).split('/').pop() ?? 'object';
  }
  return 'unknown';
}

function formatDefault(property: Record<string, unknown>): string {
  return property['default'] === undefined ? '—' : `\`${JSON.stringify(property['default'])}\``;
}

function describe(property: Record<string, unknown>): string {
  const notes: string[] = [];
  if (typeof property['description'] === 'string') notes.push(property['description']);
  if (typeof property['minimum'] === 'number') notes.push(`min ${property['minimum']}`);
  if (typeof property['maximum'] === 'number') notes.push(`max ${property['maximum']}`);
  return notes.join('; ') || '—';
}
